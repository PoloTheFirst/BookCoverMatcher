def _sheet_xml() -> str:
    def inline(ref: str, text: str) -> str:
        escaped = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        return '<c r="%s" t="inlineStr"><is><t>%s</t></is></c>' % (ref, escaped)

    rows = ['<row r="1">' + "".join(
        inline("%s1" % column, column) for column in COLUMNS) + "</row>"]
    for offset, record in enumerate(RECORDS, start=2):
        cells = []
        for column, value in zip(COLUMNS, record):
            if value == "":
                continue
            ref = "%s%d" % (column, offset)
            if value.isdigit() and column in NUMERIC:
                cells.append('<c r="%s"><v>%s</v></c>' % (ref, value))
            else:
                cells.append(inline(ref, value))
        rows.append('<row r="%d">' % offset + "".join(cells) + "</row>")
    return (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
        "<worksheet " + SPREADSHEETML_NS + ' xmlns:r="' + REL_TYPE + '">\n'
        '<dimension ref="A1:X4"/>\n<sheetData>\n' + "\n".join(rows) + "\n</sheetData>\n"
        '<drawing r:id="rId1"/>\n</worksheet>\n'
    )


def _rels(entries: list) -> str:
    body = "".join(
        '<Relationship Id="rId%d" Type="%s%s" Target="%s"/>' % (index, REL_TYPE, kind, target)
        for index, (kind, target) in enumerate(entries, start=1)
    )
    return ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            "<Relationships " + REL_NS + ">" + body + "</Relationships>")


