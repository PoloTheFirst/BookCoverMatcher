def write_workbook(path: Path) -> int:
    """A compact synthetic catalogue workbook the production reader can open.

    Reproduces the structure the reader and the comment/image scanner walk — a `LIST` sheet with the
    24 columns A–X, a header row plus three records, date columns as serial numbers, a hyperlink, an
    embedded PNG behind a drawing anchor and a comment part — with invented titles and dates only.
    """
    import zipfile

    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, body in _workbook_parts(_synthetic_png()):
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o600 << 16
            archive.writestr(info, body if isinstance(body, bytes) else body.encode("utf-8"))
    return path.stat().st_size


def _synthetic_png() -> bytes:
    import io

    from PIL import Image, ImageDraw

    image = Image.new("RGB", (96, 96), (38, 74, 124))
    draw = ImageDraw.Draw(image)
    draw.rectangle([8, 8, 88, 40], fill=(198, 60, 52))
    draw.text((10, 58), "SYNTH", fill=(255, 255, 255))
    buffer = io.BytesIO()
    image.save(buffer, "PNG")
    return buffer.getvalue()


def targets() -> list:
    """Path -> bytes for every generated fixture, in a stable order."""
    dlsite_items = [dlsite_item(*item) for item in DL_ITEMS]
    melon_items = [melonbooks_item(*item) for item in MB_ITEMS]
    return [
        (FIXTURES / "dlsite_books_search.html",
         dlsite_page(dlsite_items, empty=False).encode("utf-8")),
        (FIXTURES / "dlsite_books_empty.html", dlsite_page([], empty=True).encode("utf-8")),
        (FIXTURES / "melonbooks_search.html",
         melonbooks_page(melon_items, empty=False).encode("utf-8")),
        (FIXTURES / "melonbooks_empty.html", melonbooks_page([], empty=True).encode("utf-8")),
    ]


def main() -> int:
    import hashlib
    import tempfile

    parser = argparse.ArgumentParser()
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()

    cover = ROOT / "app/src/androidTest/assets/cover.jpg"
    workbook = ROOT / "test_excel/synthetic_catalog.xlsx"

    with tempfile.TemporaryDirectory() as directory:
        scratch = Path(directory)
        cover_file = scratch / "cover.jpg"
        workbook_file = scratch / "synthetic_catalog.xlsx"
        write_cover(cover_file)
        write_workbook(workbook_file)
        entries = list(targets()) + [
            (cover, cover_file.read_bytes()),
            (workbook, workbook_file.read_bytes()),
        ]

    print("%-52s %10s  %s" % ("path", "bytes", "sha256"))
    for path, body in entries:
        digest = hashlib.sha256(body).hexdigest()
        print("%-52s %10d  %s" % (str(path.relative_to(ROOT)).replace("\\", "/"), len(body), digest[:16]))
        if args.apply:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(body)
    print("\n%d fixture(s) %s" % (len(entries), "written" if args.apply else "would be written"))
    return 0


