def write_cover(path: Path) -> int:
    """A synthetic 600x850 book cover: flat colour blocks and large Latin text.

    Contains no third-party artwork. Large high-contrast text keeps it usable as the OCR input the
    device tests need, which is the only thing the original photograph was ever used for.
    """
    from PIL import Image, ImageDraw

    image = Image.new("RGB", (600, 850), (247, 243, 233))
    draw = ImageDraw.Draw(image)
    draw.rectangle([0, 0, 599, 849], outline=(30, 34, 40), width=6)
    draw.rectangle([40, 60, 560, 300], fill=(38, 74, 124))
    draw.rectangle([40, 340, 560, 470], fill=(198, 60, 52))
    draw.rectangle([40, 510, 560, 760], fill=(240, 236, 226), outline=(30, 34, 40), width=3)
    for x, y, text in [
        (70, 120, "SYNTHETIC"), (70, 200, "TEST COVER"), (60, 380, "BOOK COVER"),
        (60, 440, "MATCHER"), (70, 560, "SAMPLE 1"), (70, 620, "NOT A REAL BOOK"),
        (70, 680, "GPL 3.0 OR LATER"),
    ]:
        draw.text((x, y), text, fill=(255, 255, 255) if y < 500 else (30, 34, 40))
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, "JPEG", quality=82, optimize=True, progressive=False)
    return path.stat().st_size


